function G1 = computepdf_topleft(z,R,g)
%COMPUTEPDF Compute the pdf of the eigenvalue distribution in the topleft
%subpopuplation
%   Arguments:
%       z: points at which to evaluate the pdf.
%       R: a vector of firing rates as the empirical rate distribution.
%       g: variance parameter of the weight distribution.
%       eps: epsilon perturbation
%   Returns:
%       Gs: Cauchy transform of the eigenvalue distribution in the topleft
%subpopuplation

l = length(z);
G1 = zeros(1, l);
x0 = (-0.5i)*ones(1, 6);

R11 = R(1:length(R)/2);
R22 = R(length(R)/2+1:end);
R1 = R11.^(-1/2);
R2 = R22.^(-1/2);

for i = 1:l
    disp(i/l)
    % x0_guess = x0;
    % if i == 1
    %     x0_guess = (1/z(i)) * ones(1,6) * (-1i); % physical seed at large z
    % end
    Gs = fsolve(@(G) cauchyeq(z(i), R1, R2, g, G), x0,...
                  optimoptions('fsolve','display','off'));
    % x0 = Gs; % soft update
    
    % M9
    G23 = Gs(1); G45 = Gs(2); G67 = Gs(3); G89 = Gs(4); % G23 is really G2233
    G2637 = Gs(5); G4859 = Gs(6); 
    num = (2*g^6 *(G2637^2 - G23 *G67) *G89 - g^8* (G2637^2 - G23 *G67) *(G4859^2 - G45 *G89) + 8 *g^2* G23 *R1.^2 + 4* g^4 *(G23 *G45 + 2* G2637* G4859 + G67* G89)* R1.^2 - 16* R1.^4);
    denom = (-g^8 *(G2637^2 - G23 *G67) *(G4859^2 - G45* G89)* z(i) +8* g^2 *R1.^2 *(G45 + 2* G4859 + G89 + G23* z(i)) - 16* R1.^2 .*(-1 + R1.^2* z(i)) + 4* g^4 *(G67* G89 *(-1 + R1.^2 *z(i)) + G23* (-G89 + G45* R1.^2* z(i)) + 2 *G2637 *(G89 + G4859 *R1.^2 *z(i))) + 2 *g^6 *(-2* G2637 *G4859^2 + G4859^2* G67 + 2 *G2637* G45 *G89 - G45* G67 *G89 + G2637^2* G89 *z(i) + G23*(G4859^2 - G89 *(G45 + G67* z(i)))));

    G1(i) = mean(num./denom);
end
end

function f = cauchyeq(z, R1, R2, g, Gs)
%CAUCHYEQ The equation for the Cauchy transform G at z

G23 = Gs(1); G45 = Gs(2); G67 = Gs(3); G89 = Gs(4); % G23 is really G2233
G2637 = Gs(5); G4859 = Gs(6); 

frac1 = -((4 *g^4*(G2637^2 - G23* G67) + 2* g^6 *(G2637^2 - G23* G67) *G89 + 8 *g^2* G23 *R2.^2)./(2* g^6 *G45* (G2637^2 - G23* G67) - g^8* (G2637^2 - G23* G67) *(G4859^2 - G45 *G89) + 8 *g^2 *G67 *R2.^2 + 4 *g^4 *(G23 *G45 + 2 *G2637 *G4859 + G67 *G89) *R2.^2 - 16* R2.^4));
frac2 = (-4 *g^4* (G23 - 2* G2637 + G67) *G89 + 16* R1.^2 + 2* g^6* (G2637^2 - G23* G67) *G89* z + 8* g^2* G23 *R1.^2 *z)./(g^8* (G2637^2 - G23 *G67)* (G4859^2 - G45* G89) *z - 8 *g^2* R1.^2.* (G45 + 2* G4859 + G89 + G23* z) + 16* R1.^2 .*(-1 + R1.^2* z) - 4 *g^4* (G67 *G89* (-1 + R1.^2* z) + G23 *(-G89 + G45*R1.^2* z) + 2* G2637 *(G89 + G4859* R1.^2 *z)) - 2 *g^6* (-2* G2637 *G4859^2 + G4859^2 *G67 + 2 *G2637 *G45* G89 - G45* G67 *G89 + G2637^2 *G89* z + G23* (G4859^2 - G89 *(G45 + G67 *z))));
f1 = -G23+mean(frac1)+mean(frac2);

frac1 = (-4* g^4 *G45* G67 + 2 *g^6 *G67 *(G4859^2 - G45*G89) + 8* g^2* G45* R2.^2)./(-2* g^6* G45*(G2637^2 - G23* G67) + g^8 *(G2637^2 - G23* G67)* (G4859^2 - G45 *G89) - 8* g^2* G67 *R2.^2 -4* g^4* (G23 *G45 + 2* G2637 *G4859 + G67* G89)* R2.^2 + 16 *R2.^4);
frac2 = (-2* g^6 *G67* (G4859^2 - G45* G89)* z - 16 *R1.^2* z + 8 *g^2 *(G89 - G45 *R1.^2* z) + g^4 *(-4 *G4859^2 + 4 *G89 *(G45 + G67* z)))./(-g^8 *(G2637^2 - G23 *G67) *(G4859^2 - G45* G89)* z + 8* g^2* R1.^2 *(G45 + 2* G4859 + G89 + G23* z) - 16 *R1.^2.* (-1 + R1.^2 *z) + 4* g^4 *(G67* G89* (-1 + R1.^2 *z) + G23* (-G89 + G45 *R1.^2* z) + 2* G2637* (G89 + G4859 *R1.^2 *z)) + 2* g^6 *(-2* G2637* G4859^2 + G4859^2* G67 + 2* G2637* G45* G89 - G45*G67* G89 + G2637^2* G89* z + G23* (G4859^2 - G89* (G45 + G67 *z))));
f2 = -G45+mean(frac1)+mean(frac2);

frac1 = (-2* g^6 *G45 *(G2637^2 - G23 *G67) - 8 *g^2 *G67* R2.^2)./(2 *g^6* G45 *(G2637^2 - G23* G67) -g^8 *(G2637^2 - G23 *G67) *(G4859^2 - G45* G89) + 8 *g^2 *G67* R2.^2 +4 *g^4 *(G23 *G45 + 2 *G2637* G4859 + G67 *G89)* R2.^2 - 16* R2.^4);
frac2 =(2 *(8* R1.^2 + g^6* G45 *(G2637^2 - G23* G67)* z - 4 *g^2 *(G23 - 2 *G2637 + G67 - G67* R1.^2 *z) - 2* g^4* (-2* G2637* G45 + G45 *G67 - G2637^2 *z + G23 *(G45 + G67 *z))))./(g^8* (G2637^2 - G23* G67)* (G4859^2 - G45* G89) *z - 8 *g^2* R1.^2 *(G45 + 2 *G4859 + G89 + G23* z) + 16 *R1.^2 .*(-1 + R1.^2 *z) - 4 *g^4 *(G67* G89 *(-1 + R1.^2* z) + G23* (-G89 + G45* R1.^2* z) + 2*G2637 *(G89 + G4859 *R1.^2 *z)) - 2* g^6 *(-2* G2637* G4859^2 + G4859^2* G67 + 2* G2637 *G45 *G89 - G45* G67* G89 + G2637^2* G89 *z + G23 *(G4859^2 - G89* (G45 + G67 *z))));
f3 = -G67+mean(frac1)+mean(frac2);

frac1 = (-4 *g^4 *G23 *G45 + 2 *g^6* G23 *(G4859^2 - G45 *G89) + 16 *R2.^2 + 8 *g^2* G89 *R2.^2)./(-2* g^6 *G45 *(G2637^2 - G23 *G67) + g^8* (G2637^2 - G23* G67) *(G4859^2 - G45* G89) - 8 *g^2 *G67 *R2.^2 - 4* g^4 *(G23 *G45 + 2* G2637* G4859 + G67* G89)* R2.^2 + 16 *R2.^4);
frac2 = (2 *g^2* (g^4* G23 *(G4859^2 - G45* G89) *z + 4* G89 *(-1 + R1.^2 *z) + 2 *g^2 *(G4859^2 - G89 *(G45 + G23* z))))./(-g^8* (G2637^2 - G23 *G67) *(G4859^2 - G45* G89)* z + 8 *g^2* R1.^2 *(G45 + 2 *G4859 + G89 + G23 *z) - 16* R1.^2.* (-1 + R1.^2* z) + 4* g^4 *(G67 *G89 *(-1 + R1.^2* z) + G23 *(-G89 + G45* R1.^2 *z) + 2* G2637 *(G89 + G4859* R1.^2* z)) + 2 *g^6 *(-2* G2637 *G4859^2 + G4859^2* G67 + 2 *G2637* G45* G89 - G45* G67 *G89 + G2637^2 *G89* z + G23 *(G4859^2 - G89* (G45 + G67 *z))));
f4 = -G89+mean(frac1)-mean(frac2);

frac1 = (-2 *g^6* G4859 *(G2637^2 - G23* G67) + 8* g^2 *G2637 *R2.^2)./(-2* g^6* G45 *(G2637^2 - G23* G67) + g^8* (G2637^2 - G23 *G67) *(G4859^2 - G45* G89) - 8 *g^2 *G67* R2.^2 - 4* g^4 *(G23* G45 + 2* G2637* G4859 + G67 *G89)* R2.^2 + 16* R2.^4);
frac2 = (2* (2* g^4* G4859* (G23 - 2 *G2637 + G67) + 8* R1.^2 + g^6 *G4859* (-G2637^2 + G23 *G67)* z + 4* g^2 *G2637* R1.^2 *z))./(-g^8 *(G2637^2 - G23 *G67)* (G4859.^2 - G45 *G89)* z + 8 *g^2* R1.^2 *(G45 + 2* G4859 + G89 + G23* z) - 16 *R1.^2 .*(-1 + R1.^2* z) + 4 *g^4* (G67 *G89 *(-1 + R1.^2* z) + G23 *(-G89 + G45* R1.^2* z) + 2 *G2637 *(G89 + G4859 *R1.^2* z)) +2 *g^6 *(-2 *G2637 *G4859^2 + G4859^2* G67 + 2* G2637* G45 *G89 - G45* G67* G89 + G2637^2* G89 *z + G23* (G4859^2 - G89 *(G45 + G67 *z))));
f5 = -G2637+mean(frac1)-mean(frac2);

frac1 = 2*g^2* (-2 *g^2* G2637 *G45 + g^4 *G2637 *(G4859^2 - G45* G89) - 4 *G4859* R2.^2)./(2* g^6 *G45* (G2637^2 - G23* G67) - g^8* (G2637^2 - G23* G67)* (G4859^2 - G45* G89) + 8 *g^2 *G67* R2.^2 + 4 *g^4 *(G23* G45 + 2 *G2637* G4859 + G67 *G89)* R2.^2 - 16* R2.^4);
frac2 = 2 *g^2* ((g^4 *G2637* (-G4859^2 + G45* G89)* z + 4 *(G89 + G4859 *R1.^2 *z) + g^2* (-2 *G4859^2 + 2 *G89* (G45 + G2637* z)))./(g^8* (G2637^2 - G23* G67)* (G4859^2 - G45* G89)* z - 8 *g^2* R1.^2* (G45 + 2 *G4859 + G89 + G23 *z) + 16* R1.^2.* (-1 + R1.^2* z) - 4* g^4* (G67* G89 *(-1 + R1.^2* z) + G23* (-G89 + G45* R1.^2 *z) + 2 *G2637* (G89 + G4859* R1.^2 *z)) - 2* g^6* (-2 *G2637 *G4859^2 + G4859^2 *G67 + 2* G2637 *G45 *G89 - G45* G67 *G89 + G2637^2* G89* z + G23* (G4859^2 - G89 *(G45 + G67* z)))));
f6 = -G4859+mean(frac1)+mean(frac2);

f = [f1, f2, f3, f4, f5, f6];
end
